import React from 'react';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import Page from './SendWhatsappPingPage';
import ep1 from '../api/ep1';
jest.mock('../api/ep1', () => ({ get: jest.fn(), post: jest.fn() }));
jest.mock('./global1', () => ({ colid: 42, email: 'admin@example.com' }));
jest.mock('./MenuPageShell', () => ({ children }) => <div>{children}</div>);
jest.mock('@mui/x-data-grid', () => ({ DataGrid: props => props.checkboxSelection ? <button onClick={() => props.onRowSelectionModelChange(['student1'])}>Select student</button> : null, GridToolbar: () => null }));
test('loads Ping options and sends selected template variables through the backend', async () => {
  ep1.get.mockResolvedValue({ data: { configs: [{_id:'config1',phoneid:'123'}], templates:[{_id:'template1',templatename:'Welcome',templatecode:'welcome_ping',noofvariables:1,variablenames:'Student name'}],balance:10 } });
  ep1.post.mockImplementation(url => Promise.resolve({data:url.endsWith('/users') ? {data:[{_id:'student1',name:'Student',phone:'9008168822'}]} : {recipients:[{name:'Student',phone:'919008168822',status:'Accepted'}],balance:9}}));
  jest.spyOn(window,'confirm').mockReturnValue(true);
  render(<Page />);
  await screen.findByText('WhatsApp credits: 10');
  fireEvent.mouseDown(screen.getByRole('combobox',{name:'Ping template'}));
  fireEvent.click(await screen.findByRole('option',{name:'Welcome (welcome_ping)'}));
  fireEvent.change(screen.getByLabelText(/1. Student name/),{target:{value:'Prakash'}});
  fireEvent.click(screen.getByRole('button',{name:'Load users'}));
  await waitFor(()=>expect(ep1.post).toHaveBeenCalledWith('/api/v2/bhash-whatsapp/users',expect.objectContaining({colid:42})));
  fireEvent.click(screen.getByRole('button',{name:'Select student'}));
  fireEvent.click(screen.getByRole('button',{name:'Send WhatsApp Ping'}));
  await waitFor(()=>expect(ep1.post).toHaveBeenCalledWith('/api/v2/ping-whatsapp/send',expect.objectContaining({colid:42,configid:'config1',templateid:'template1',values:['Prakash'],language:'en',userids:['student1']}),expect.any(Object)));
  await screen.findByText(/1 accepted by Ping/);
  window.confirm.mockRestore();
});
test('direct Ping accepts typed phone numbers and does not load a user list', async () => {
  ep1.get.mockResolvedValue({ data: { configs:[{_id:'config1',phoneid:'123'}],templates:[{_id:'template1',templatename:'Welcome',templatecode:'welcome_ping',noofvariables:0}],balance:10 } });
  ep1.post.mockClear();
  ep1.post.mockResolvedValue({data:{recipients:[{phone:'919008168822',status:'Accepted'}],balance:9}});
  jest.spyOn(window,'confirm').mockReturnValue(true);
  render(<Page direct />);
  await screen.findByText('WhatsApp credits: 10');
  expect(screen.queryByRole('button',{name:'Load users'})).not.toBeInTheDocument();
  fireEvent.change(screen.getByLabelText('Phone numbers'),{target:{value:'9008168822, +919008168822'}});
  fireEvent.mouseDown(screen.getByRole('combobox',{name:'Ping template'}));
  fireEvent.click(await screen.findByRole('option',{name:'Welcome (welcome_ping)'}));
  fireEvent.click(screen.getByRole('button',{name:'Send WhatsApp Ping'}));
  await waitFor(()=>expect(ep1.post).toHaveBeenCalledWith('/api/v2/ping-whatsapp/send-direct',expect.objectContaining({colid:42,mobileNumbers:'919008168822',templateid:'template1'}),expect.any(Object)));
  await screen.findByText(/1 accepted by Ping/);
  window.confirm.mockRestore();
});
